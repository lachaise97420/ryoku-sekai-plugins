#!/bin/sh

mode="$1"
dir="${XDG_STATE_HOME:-$HOME/.local/state}/ryoku/plugins/sekai-visualizer"
file="$dir/visualizer.json"

case "$mode" in
    save)
        mkdir -p "$dir" || exit 1
        printf '%s\n' "$2" > "$file.tmp" || exit 1
        mv "$file.tmp" "$file"
        ;;
    load)
        [ -f "$file" ] && cat "$file"
        exit 0
        ;;
    *)
        echo "usage: $0 save <json>|load" >&2
        exit 2
        ;;
esac
